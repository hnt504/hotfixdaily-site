#!/usr/bin/env python3
"""Build Hotfix Daily from source.

Source of truth:
  content/issues/issue-NNN.md   issues (the format in PUBLISHING.md)
  content/pages/**.html         every other page: front matter + the page body
  templates/                    shared layout, issue page, feeds, llms files
  site.yml                      site settings and sitemap order

Everything else at the repo root (index.html, issues/, guides/..., feed.xml,
rss.xml, sitemap.xml, llms.txt, llms-full.txt) is generated by this script.

  python3 tools/build.py                       build everything
  python3 tools/build.py --check               report what would change, write nothing
  python3 tools/build.py --email NNN [--stdout | --out FILE]
                                               the Kit email HTML for one issue
  python3 tools/build.py --reimport-from REV   first pull in pages a bot edited as HTML since REV
"""

from __future__ import annotations

import argparse
import datetime as dt
import hashlib
import html
import json
import re
import subprocess
import sys
import urllib.parse
from pathlib import Path

import jinja2
import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
import issues as iss  # noqa: E402
from importer import import_page, route_of, split_front_matter  # noqa: E402
from issue_import import issue_html_to_markdown  # noqa: E402

BASE = "https://hotfixdaily.com"


# ------------------------------------------------------------------ helpers

def write(path: Path, text: str, changed: list[str], dry: bool) -> None:
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old == text:
        return
    changed.append(str(path.relative_to(ROOT)))
    if not dry:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


def git_date(path: Path) -> str | None:
    try:
        out = subprocess.run(["git", "log", "-1", "--format=%cs", "--", str(path)], cwd=ROOT,
                             capture_output=True, text=True, check=True).stdout.strip()
        return out or None
    except Exception:
        return None


def page_url(route: str) -> str:
    if route == "index":
        return f"{BASE}/"
    if route == "404":
        return f"{BASE}/404.html"
    return f"{BASE}/{route}/"


def page_out(route: str) -> str:
    if route == "index":
        return "index.html"
    if route == "404":
        return "404.html"
    return f"{route}/index.html"


# ------------------------------------------------------------------ loading

def load_issues() -> list[dict]:
    issues = []
    for p in sorted((ROOT / "content" / "issues").glob("issue-[0-9]*.md")):
        d = iss.parse_issue(str(p))
        if d["draft"]:
            continue
        d["path"] = f"/issues/{d['slug']}/"
        d["url"] = f"{BASE}/issues/{d['slug']}/"
        d["source"] = p
        d["headlines"] = "; ".join(iss.plain(it["head"]) for it in d["items"])
        issues.append(d)
    issues.sort(key=lambda d: d["num"], reverse=True)
    return issues


def load_pages() -> dict[str, dict]:
    pages = {}
    folder = ROOT / "content" / "pages"
    for p in sorted(folder.rglob("*.html")):
        meta, body = split_front_matter(p.read_text(encoding="utf-8"))
        route = str(p.relative_to(folder))[: -len(".html")].replace("\\", "/")
        meta.update(route=route, url=page_url(route), out=page_out(route), body=body, source=p)
        pages[route] = meta
    return pages


# ------------------------------------------------------------------ safety net

def changed_since(rev: str) -> set[str]:
    out = subprocess.run(["git", "diff", "--name-only", f"{rev}..HEAD"], cwd=ROOT,
                         capture_output=True, text=True, check=True).stdout
    return {l.strip() for l in out.splitlines() if l.strip()}


def adopt_stray_html(reimport_from: str | None) -> list[str]:
    """Pull in issues and pages that arrived as finished HTML instead of source."""
    notes = []
    issue_dir = ROOT / "content" / "issues"
    for page in sorted((ROOT / "issues").glob("[0-9][0-9][0-9]/index.html")):
        n = page.parent.name
        md = issue_dir / f"issue-{n}.md"
        if not md.exists():
            md.parent.mkdir(parents=True, exist_ok=True)
            md.write_text(issue_html_to_markdown(page.read_text(encoding="utf-8")), encoding="utf-8")
            notes.append(f"imported issue published as HTML: issues/{n}/ -> content/issues/issue-{n}.md")
    if not reimport_from:
        return notes
    changed = changed_since(reimport_from)
    pages = load_pages()
    for rel in sorted(changed):
        if not rel.endswith(".html") or rel.startswith(("content/", "templates/", "issues/")):
            continue
        if not (ROOT / rel).exists():
            continue
        route = route_of(rel)
        src = f"content/pages/{route}.html"
        if src in changed:
            continue
        if route in pages and pages[route].get("dynamic"):
            notes.append(f"WARNING: {rel} was edited directly but is generated from {src}; that edit was replaced")
            continue
        import_page(ROOT, rel)
        notes.append(f"imported page edited as HTML: {rel} -> {src}")
    return notes


# ------------------------------------------------------------------ issue pieces (formats match the old pipeline)

def web_intro(d: dict) -> list[str]:
    """Intro paragraphs for the web page and feeds.

    The Markdown carries a "Read this issue on the web" link for the email. On
    the web page itself that link points at the page you're already on, so it's
    dropped there (the email keeps it).
    """
    out = []
    for para in d["intro_extra"]:
        parts = [part for part in para.split(" · ") if f"]({d['url']})" not in part]
        if parts:
            out.append("<p>%s</p>" % iss.inline(" · ".join(parts)))
    return out


def feed_content(d: dict) -> str:
    return "\n".join(web_intro(d) + iss.render_items_html(d)) + "\n"


def archive_item(d: dict) -> str:
    return '<article class="arch"><h2><a href="%s">Hotfix Daily #%d</a></h2><p class="muted"><time datetime="%s">%s</time></p><ul>%s</ul></article>' % (
        d["path"], d["num"], d["date"].isoformat(), iss.tesc(d["date_h"]),
        "".join('<li><span class="chip">%s</span> %s</li>' % (iss.esc(it["label"]), iss.esc(iss.plain(it["head"]))) for it in d["items"]))


def latest_block(d: dict) -> str:
    lt = "".join('<li><span class="chip">%s</span> <a href="%s#i%d">%s</a></li>' % (
        iss.esc(it["label"]), d["path"], it["n"], iss.esc(iss.plain(it["head"]))) for it in d["items"])
    blk = ['<h2>Latest issue: <a href="%s">Hotfix Daily #%d</a> <span class="muted small"><time datetime="%s">%s</time></span></h2>' % (
        d["path"], d["num"], d["date"].isoformat(), iss.tesc(d["date_h"])), '<ul class="lt">%s</ul>' % lt]
    t = iss.hotd_teaser(d)
    if t:
        blk.append('<p class="hotd-mini"><a href="%s#hotd"><strong>Hotfix of the Day:</strong></a> %s</p>' % (d["path"], iss.esc(t)))
    blk.append('<p><a href="%s">Read the full issue →</a> · <a href="/issues/">All issues</a></p>' % d["path"])
    return "\n".join(blk)


def issue_jsonld(d: dict) -> list[str]:
    iso = d["date"].isoformat()
    article = {"@context": "https://schema.org", "@type": "NewsArticle", "headline": d["title"], "description": d["description"],
               "datePublished": iso, "dateModified": iso, "url": d["url"], "mainEntityOfPage": d["url"],
               "image": BASE + "/assets/og.png", "author": {"@id": BASE + "/#org"}, "publisher": {"@id": BASE + "/#org"},
               "isPartOf": {"@id": BASE + "/#website"}, "about": [iss.plain(it["head"]) for it in d["items"]]}
    crumbs = {"@context": "https://schema.org", "@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": 1, "name": "Home", "item": BASE + "/"},
        {"@type": "ListItem", "position": 2, "name": "Issues", "item": BASE + "/issues/"},
        {"@type": "ListItem", "position": 3, "name": "Issue #%d" % d["num"], "item": d["url"]}]}
    return [iss.jdump(article), iss.jdump(crumbs)]


def feed_entry(d: dict) -> str:
    ts = d["date"].isoformat() + "T11:00:00Z"
    return ("<entry>\n<title>%s</title>\n<link rel=\"alternate\" type=\"text/html\" href=\"%s\"/>\n<id>%s</id>\n<published>%s</published>\n<updated>%s</updated>\n"
            "<summary>%s</summary>\n<content type=\"html\">%s</content>\n</entry>\n") % (
        iss.esc(d["title"]), d["url"], d["url"], ts, ts, iss.esc(d["description"]), iss.esc(feed_content(d)))


def rfc822(d: dict) -> str:
    return dt.datetime.combine(d["date"], dt.time(11, 0)).strftime("%a, %d %b %Y %H:%M:%S +0000")


def rss_item(d: dict) -> str:
    return ("<item>\n<title>%s</title>\n<link>%s</link>\n<guid isPermaLink=\"true\">%s</guid>\n<pubDate>%s</pubDate>\n<description>%s</description>\n"
            "<content:encoded><![CDATA[%s]]></content:encoded>\n</item>\n") % (
        iss.esc(d["title"]), d["url"], d["url"], rfc822(d), iss.esc(d["description"]), feed_content(d))


# ------------------------------------------------------------------ build

def _text(fragment: str) -> str:
    return html.unescape(re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", fragment))).strip()


def sync_faq_jsonld(raw: str, body: str) -> str:
    """Keep FAQPage structured data identical to the FAQ visitors see.

    The questions and answers come from the page's <details><summary> FAQ, so
    editing the FAQ on the page is enough; the JSON-LD follows.
    """
    if '"FAQPage"' not in raw:
        return raw
    pairs = re.findall(r"<details[^>]*><summary>([\s\S]*?)</summary>([\s\S]*?)</details>", body)
    if not pairs:
        return raw
    data = json.loads(raw)
    data["mainEntity"] = [{"@type": "Question", "name": _text(q),
                           "acceptedAnswer": {"@type": "Answer", "text": _text(a)}} for q, a in pairs]
    if '": "' in raw:
        return json.dumps(data, ensure_ascii="\\u" in raw)
    return json.dumps(data, ensure_ascii="\\u" in raw, separators=(",", ":"))


def make_env() -> jinja2.Environment:
    env = jinja2.Environment(loader=jinja2.FileSystemLoader(ROOT / "templates"), autoescape=False,
                             keep_trailing_newline=True, trim_blocks=True)
    env.filters["esc"] = lambda v: html.escape(str(v), quote=True)
    env.filters["tesc"] = lambda v: html.escape(str(v), quote=False)
    return env


def sitemap(site: dict, pages: dict, issues: list[dict]) -> str:
    listed = {r for r, *_ in site["sitemap"] if not r.endswith("*")}
    newest = issues[0]["date"].isoformat() if issues else dt.date.today().isoformat()
    rows = []

    def row(url, lastmod, freq, prio):
        rows.append(f"  <url><loc>{url}</loc><lastmod>{lastmod}</lastmod><changefreq>{freq}</changefreq><priority>{prio}</priority></url>")

    def page_row(route, freq, prio):
        p = pages[route]
        if p.get("noindex"):
            return
        lastmod = str(p.get("updated") or "") or (newest if route in ("index", "issues") else git_date(p["source"]) or newest)
        row(p["url"], lastmod, freq, prio)

    for route, freq, prio in site["sitemap"]:
        if route == "issues/*":
            # an issue page last changed when the next issue added its "Issue #N+1 →" link
            for k, d in enumerate(issues):
                lastmod = issues[k - 1]["date"] if k > 0 else d["date"]
                row(d["url"], lastmod.isoformat(), freq, prio)
        elif route.endswith("/*"):
            prefix = route[:-1]
            for r in pages:
                if r.startswith(prefix) and r not in listed:
                    page_row(r, freq, prio)
        elif route in pages:
            page_row(route, freq, prio)
    return '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + "\n".join(rows) + "\n</urlset>\n"


def build(dry: bool) -> tuple[list[str], list[str]]:
    site = yaml.safe_load((ROOT / "site.yml").read_text(encoding="utf-8"))
    issues = load_issues()
    pages = load_pages()
    if not issues:
        raise SystemExit("ERROR: no published issues in content/issues/; refusing to build")
    latest = issues[0]
    env = make_env()
    changed: list[str] = []
    base = env.get_template("base.html")
    css_query = "?v=" + hashlib.sha256((ROOT / "assets" / "style.css").read_bytes()).hexdigest()[:8]

    ctx = {
        "site": site, "issues": issues, "latest": latest, "latest_block": latest_block(latest),
        "archive_items": [archive_item(d) for d in issues],
        "archive_ld": iss.jdump({"@context": "https://schema.org", "@type": "CollectionPage", "name": "Hotfix Daily archive",
                                 "url": BASE + "/issues/", "isPartOf": {"@id": BASE + "/#website"},
                                 "mainEntity": {"@type": "ItemList", "itemListElement": [
                                     {"@type": "ListItem", "position": k + 1, "url": d["url"], "name": d["title"]}
                                     for k, d in enumerate(issues)]}}),
    }

    # guide and tool listings, from each page's `listing:` front matter
    listed = sorted((p for p in pages.values() if p.get("listing")), key=lambda p: p["listing"].get("order", 0))
    for p in listed:
        L = p["listing"]
        p["path"] = p["url"][len(BASE):]
        p["llms_title"] = L.get("llms_title", p["title"])
        p["llms_blurb"] = L.get("llms_blurb", p["description"])
    ctx["home_guide_cards"] = "".join(
        '<a class="card link" href="%s"><h3>%s</h3><p>%s</p></a>' % (p["path"], iss.esc(p["listing"]["home_title"]), iss.esc(p["description"]))
        for p in listed if p["listing"].get("home_title"))
    ctx["index_guide_cards"] = "".join(
        '<a class="card link" href="%s"><h2>%s</h2><p>%s</p></a>' % (
            p["path"], iss.esc(p["listing"].get("index_title", p["title"])), iss.esc(p["listing"].get("index_blurb", p["description"])))
        for p in listed)
    guides_only = [p for p in listed if p["listing"]["kind"] == "guide"]
    ctx["guides_ld"] = iss.jdump({"@context": "https://schema.org", "@type": "CollectionPage", "name": "Hotfix Daily guides",
                                  "url": BASE + "/guides/", "mainEntity": {"@type": "ItemList", "itemListElement": [
                                      {"@type": "ListItem", "position": k + 1, "url": p["url"], "name": p["title"]}
                                      for k, p in enumerate(guides_only)]}})
    ctx["tools"] = [p for p in listed if p["listing"]["kind"] == "tool"]
    ctx["guides_and_extras"] = [p for p in listed if p["listing"]["kind"] in ("guide", "extra")]

    def render_str(s, **extra):
        return env.from_string(s).render(**ctx, **extra)

    # pages
    for route, p in pages.items():
        if p.get("jsonld"):
            p["jsonld"] = [sync_faq_jsonld(j, p["body"]) for j in p["jsonld"]]
        page = dict(p)
        if p.get("dynamic"):
            page["title"] = render_str(p["title"])
            page["description"] = render_str(p["description"])
            page["jsonld"] = [render_str(j) for j in p.get("jsonld") or []]
            body = render_str(p["body"])
        else:
            body = p["body"]
        out = base.render(site=site, page=page, main=body.rstrip("\n"), css_query=css_query)
        write(ROOT / p["out"], out, changed, dry)

    # issues
    tpl = env.get_template("issue.html")
    for k, d in enumerate(issues):
        newer = issues[k - 1]["num"] if k > 0 else None
        older = issues[k + 1]["num"] if k + 1 < len(issues) else None
        share = "https://x.com/intent/post?text=%s&url=%s" % (
            urllib.parse.quote(d["title"] + " (via @hotfixdaily)", safe=""), urllib.parse.quote(d["url"], safe=""))
        main = tpl.render(d=d, lede=iss.inline(d["lede"]), intro_links=web_intro(d),
                          items_html="\n".join(iss.render_items_html(d)), share=share,
                          pager=iss.pager(d["num"], older, newer))
        page = {"title": d["title"], "description": d["description"], "url": d["url"], "og_type": "article",
                "jsonld": issue_jsonld(d)}
        write(ROOT / "issues" / d["slug"] / "index.html",
              base.render(site=site, page=page, main=main.rstrip("\n"), css_query=css_query), changed, dry)

    # feeds, sitemap, llms
    write(ROOT / "feed.xml", env.get_template("feed.xml").render(
        updated=latest["date"].isoformat() + "T11:00:00Z", entries="".join(feed_entry(d) for d in issues)), changed, dry)
    write(ROOT / "rss.xml", env.get_template("rss.xml").render(
        last_build=rfc822(latest), items="".join(rss_item(d) for d in issues)), changed, dry)
    write(ROOT / "sitemap.xml", sitemap(site, pages, issues), changed, dry)
    write(ROOT / "llms.txt", env.get_template("llms.txt").render(**ctx), changed, dry)
    write(ROOT / "llms-full.txt", env.get_template("llms-full.txt").render(
        llms_full_issues="\n".join(iss.llms_full_section(d) for d in issues)), changed, dry)
    return changed, list(iss.WARN)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--email", metavar="NNN")
    ap.add_argument("--stdout", action="store_true")
    ap.add_argument("--out")
    ap.add_argument("--reimport-from", metavar="REV")
    ap.add_argument("--no-adopt", action="store_true")
    args = ap.parse_args()

    if args.email:
        path = ROOT / "content" / "issues" / f"issue-{int(args.email):03d}.md"
        out = iss.render_email(iss.parse_issue(str(path)))
        for w in iss.WARN:
            print(w, file=sys.stderr)
        if args.stdout:
            sys.stdout.write(out)
        else:
            dest = Path(args.out) if args.out else ROOT / "email" / f"issue-{int(args.email):03d}.html"
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(out, encoding="utf-8")
            print(f"wrote {dest}")
        return 0

    if not args.check and not args.no_adopt:
        for note in adopt_stray_html(args.reimport_from):
            print(f"safety net: {note}")

    changed, warnings = build(dry=args.check)
    for w in warnings:
        print(w)
    verb = "would change" if args.check else "changed"
    print(f"{len(changed)} file(s) {verb}" + (":" if changed else "."))
    for c in changed:
        print(f"  {c}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
